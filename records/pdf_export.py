def _text(value):
    """
    Foydalanuvchi kiritgan matn Paragraph'ga faqat shu orqali beriladi: reportlab matnni belgilash
    sifatida o'qiydi, escape'siz yopilmagan teg 500 beradi, <img src> esa serverdagi faylni PDF'ga
    joylaydi (ZAP 2026-10-23). Qator ko'chishlari saqlanadi.
    """
    return escape(str(value)).replace("\r\n", "\n").replace("\n", "<br/>")


def _get_avatar_flowable(user, size=28 * mm):
    if not user.avatar or not hasattr(user.avatar, "path"):
        return None
    try:
        if not os.path.exists(user.avatar.path):
            return None
        # Image() faylni doc.build() paytida o'qiydi: rasm bo'lmagan fayl (eski yuklashlar) butun PDF'ni
        # yiqitmasligi uchun shu yerda tekshiriladi, PDF avatarsiz yasaladi
        ImageReader(user.avatar.path).getSize()
        img = Image(user.avatar.path, width=size, height=size)
        img.hAlign = "LEFT"
        return img
    except Exception:
        return None


def _ref_text(v):
    def fmt(x):
        return None if x is None else format(x.normalize(), "f")
    lo, hi = fmt(v.ref_low), fmt(v.ref_high)
    if lo is not None and hi is not None:
        return f"{lo} - {hi}"
    if hi is not None:
        return f"<= {hi}"
    if lo is not None:
        return f">= {lo}"
    return v.ref_text or "-"


def build_patient_history_pdf(patient, records, lang="uz", lab_results=None):
    """
    Bemor va uning tibbiy yozuvlari asosida PDF baytlar oqimini (BytesIO)
    qaytaradi. `lang` — "uz", "ru" yoki "en"; noma'lum til uchun "uz"ga tushadi.
    """
    tr = TRANSLATIONS.get(lang, TRANSLATIONS["uz"])

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=20 * mm, bottomMargin=20 * mm,
        leftMargin=20 * mm, rightMargin=20 * mm,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("TitleUz", parent=styles["Title"], fontSize=16, spaceAfter=4)
    meta_style = ParagraphStyle(
        "MetaUz", parent=styles["Normal"], fontSize=9,
        textColor=colors.HexColor("#55716A"), spaceAfter=16,
    )
    section_style = ParagraphStyle(
        "SectionUz", parent=styles["Heading2"], fontSize=12,
        textColor=colors.HexColor("#0E5C56"), spaceBefore=14, spaceAfter=6,
    )
    label_style = ParagraphStyle("LabelUz", parent=styles["Normal"], fontSize=9, textColor=colors.HexColor("#55716A"))
    body_style = ParagraphStyle("BodyUz", parent=styles["Normal"], fontSize=10, leading=14)

    elements = []

    full_name = f"{patient.user.first_name} {patient.user.last_name}".strip() or patient.user.username

    header_title = Paragraph(tr["title"], title_style)
    header_meta = Paragraph(tr["meta"], meta_style)
    avatar = _get_avatar_flowable(patient.user)

    if avatar:
        header_table = Table([[[header_title, header_meta], avatar]], colWidths=[125 * mm, 30 * mm])
        header_table.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("ALIGN", (1, 0), (1, 0), "RIGHT"),
        ]))
        elements.append(header_table)
    else:
        elements.append(header_title)
        elements.append(header_meta)

    elements.append(Spacer(1, 6 * mm))

    gender_display = tr.get(f"gender_{patient.gender}", tr["not_set"]) if patient.gender else tr["not_set"]

    profile_data = [
        [tr["full_name"], full_name],
        [tr["birth_date"], str(patient.date_of_birth) if patient.date_of_birth else tr["not_set"]],
        [tr["gender"], gender_display],
        [tr["blood_type"], patient.blood_type or tr["not_set"]],
        [tr["allergies"], patient.allergies or tr["not_set"]],
    ]
    profile_table = Table(profile_data, colWidths=[45 * mm, 110 * mm])
    profile_table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#55716A")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE6E2")),
    ]))
    elements.append(profile_table)
    elements.append(Spacer(1, 10 * mm))

    # Tahlil natijalari: har bir turdan eng oxirgi amaldagisi (tanlash records/views.py da)
    lab_results = lab_results or []
    elements.append(Paragraph(tr["labs_title"], section_style))
    elements.append(Paragraph(tr["labs_note"], label_style))
    elements.append(Spacer(1, 2 * mm))
    if not lab_results:
        elements.append(Paragraph(tr["no_labs"], body_style))
    flag_color = {"low": "#2F5FA8", "high": "#A83B3B", "abnormal": "#A83B3B"}
    for lr in lab_results:
        elements.append(Paragraph(f"{lr.collected_at.strftime('%Y-%m-%d')} — {_text(lr.title)}", body_style))
        by = _text(lr.created_by.get_full_name() or lr.created_by.username)
        valid = f" · {tr['valid_until']}: {lr.valid_until}" if lr.valid_until else ""
        elements.append(Paragraph(f"{tr['lab_by']}: {by}{valid}", label_style))
        rows = [[Paragraph(f"<b>{_text(c)}</b>", label_style) for c in tr["lab_cols"]]]
        for v in lr.values.all():
            flag = v.flag
            value = _text(v.value)
            if flag in flag_color:
                value = f'<font color="{flag_color[flag]}"><b>{value}</b> ({tr["flag_" + flag]})</font>'
            rows.append([Paragraph(_text(v.name), body_style), Paragraph(value, body_style),
                         Paragraph(_text(v.unit or ""), body_style), Paragraph(_text(_ref_text(v)), body_style)])
        t = Table(rows, colWidths=[55 * mm, 45 * mm, 22 * mm, 33 * mm], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#ECF2EF")),
            ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#DCE6E2")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        elements.append(t)
        elements.append(Spacer(1, 4 * mm))
    elements.append(Spacer(1, 4 * mm))

    elements.append(Paragraph(tr["records_title"].format(count=len(records)), section_style))

    if not records:
        elements.append(Paragraph(tr["no_records"], body_style))
    else:
        for r in records:
            record_title = f"{r.visit_date.strftime('%Y-%m-%d')} — {_text(r.title)}"
            elements.append(Paragraph(record_title, section_style))
            type_label = _text(tr["record_types"].get(r.record_type, r.record_type))
            doctor_name = _text(r.created_by.get_full_name() or r.created_by.username)
            elements.append(Paragraph(f"{tr['type']}: {type_label} · {tr['doctor']}: {doctor_name}", label_style))
            if r.diagnosis:
                elements.append(Paragraph(f"<b>{tr['diagnosis']}:</b> {_text(r.diagnosis)}", body_style))
            if r.treatment:
                elements.append(Paragraph(f"<b>{tr['treatment']}:</b> {_text(r.treatment)}", body_style))
            if r.notes:
                elements.append(Paragraph(f"<b>{tr['notes']}:</b> {_text(r.notes)}", body_style))
            elements.append(Spacer(1, 4 * mm))

    doc.build(elements)
    buffer.seek(0)
    return buffer